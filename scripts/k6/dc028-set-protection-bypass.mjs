#!/usr/bin/env node
/**
 * DC-028: Register Vercel Deployment Protection bypass (not just a user env var).
 * PATCH /v1/projects/{id}/protection-bypass
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { mergeEnvLocal } from '../smoke/merge-env-local.mjs';

const PROJECT_ID = 'prj_AJZzlPmgfbDyl05B44bwfymevnri';
const TEAM_ID = 'team_xF02AHVvbtvIkbJtUzcxrKQY';

function loadVercelToken() {
  if (process.env.VERCEL_TOKEN) return process.env.VERCEL_TOKEN;
  const candidates = [
    path.join(os.homedir(), '.vercel', 'auth.json'),
    path.join(os.homedir(), 'AppData', 'Roaming', 'com.vercel.cli', 'Data', 'auth.json'),
  ];
  for (const authPath of candidates) {
    if (!fs.existsSync(authPath)) continue;
    const auth = JSON.parse(fs.readFileSync(authPath, 'utf8'));
    if (auth.token) return auth.token;
  }
  return '';
}

function generateBypassSecret() {
  const chars = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  const bytes = crypto.randomBytes(32);
  let out = '';
  for (let i = 0; i < 32; i += 1) {
    out += chars[bytes[i] % chars.length];
  }
  return out;
}

const token = loadVercelToken();
if (!token) {
  console.error('No Vercel token — run vercel login or set VERCEL_TOKEN');
  process.exit(1);
}

const secret = generateBypassSecret();
console.log('generated bypass len', secret.length, 'prefix', secret.slice(0, 6));

const res = await fetch(
  `https://api.vercel.com/v1/projects/${PROJECT_ID}/protection-bypass?teamId=${TEAM_ID}`,
  {
    method: 'PATCH',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      generate: {
        secret,
        note: 'k6 staging dry-run DC-028',
      },
    }),
  },
);

const text = await res.text();
if (!res.ok) {
  console.error('protection-bypass PATCH failed', res.status, text.slice(0, 400));
  process.exit(1);
}

console.log('protection-bypass registered OK');

mergeEnvLocal({ VERCEL_AUTOMATION_BYPASS_SECRET: secret });
fs.writeFileSync('.dc028-secret.tmp', secret, 'utf8');

spawnSync('vercel', ['env', 'rm', 'VERCEL_AUTOMATION_BYPASS_SECRET', 'staging', '--yes'], {
  shell: true,
  stdio: 'pipe',
  encoding: 'utf8',
});
